function normalizeMapLocale(locale: string): string {
  const clean = (locale || "fr").toLowerCase().split("-")[0];
  return clean === "fr" || GOV_ENRICHMENT_LOCALES[clean] ? clean : "fr";
}

export function getLocalizedGovEnrichment(
  govId: string,
  locale = "fr"
): GovernorateArchivalDetail | null {
  const base = GOV_ARCHIVAL_ENRICHMENT[govId];
  if (!base) return null;
  const clean = normalizeMapLocale(locale);
  if (clean === "fr") return base;
  const trans = GOV_ENRICHMENT_LOCALES[clean]?.[govId];
  if (!trans) return base;
  return {
    ...base,
    ...trans,
  };
}

