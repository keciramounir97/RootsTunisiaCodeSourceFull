const FR_REGION_FIXUPS: Record<string, Partial<MaghrebRegionTranslation>> = {
  "Sfax & South Coast": { name: "Sfax & Côte Sud" },
  "Gabès & Gulf": { name: "Gabès & Golfe" },
  "Tataouine & Extreme Sud": { name: "Tataouine & Extrême-Sud" },
  "Rabat & Gharb": { tribes: "Zaër, Gharbaoui, Cherkaoui, lignées andalouses" },
  "Alger & Mitidja": { tribes: "Deylik, Mitidji, Belkacem, familles andalouses" },
};

export function localizeMaghrebRegion<T extends MaghrebRegionTranslation>(
  region: T,
  locale = "fr"
): T {
  const clean = (locale || "fr").toLowerCase().split("-")[0];
  if (clean === "fr") {
    const fix = FR_REGION_FIXUPS[region.name];
    return fix ? { ...region, ...fix } : region;
  }
  const tr = MAGHREB_MAP_LOCALES[clean]?.regions[region.name];
  return tr ? { ...region, ...tr } : region;
}

export function localizeMaghrebCity<T extends MaghrebCityTranslation>(
  city: T,
  locale = "fr"
): T {
  const clean = (locale || "fr").toLowerCase().split("-")[0];
  if (clean === "fr") return city;
  const tr = MAGHREB_MAP_LOCALES[clean]?.cities[city.name];
  return tr ? { ...city, ...tr } : city;
}

